import { test, expect } from '@playwright/test';

test('create, edit, filter, complete and delete a task; retain workspace through signup and login', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('/');
  await expect(page.locator('.task-row')).toHaveCount(6);
  await page.getByRole('button', { name: 'New task', exact: true }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Task name').fill('Ship the Daylight app');
  await dialog.getByLabel('Description').fill('Verify the full user journey.');
  await dialog.getByLabel('Status', { exact: true }).selectOption('In Progress');
  await dialog.getByLabel('Priority', { exact: true }).selectOption('High');
  await dialog.getByLabel('Deadline').fill('2027-01-15');
  await dialog.getByLabel('List', { exact: true }).fill('Launch');
  await dialog.getByLabel('Tags').fill('Release, Testing');
  await dialog.getByRole('button', { name: 'Create task', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  const row = page.locator('.task-row').filter({ hasText: 'Ship the Daylight app' });
  await expect(row).toContainText('In Progress');
  await expect(row).toContainText('Release');
  await page.reload();
  await expect(row).toBeVisible();
  await page.getByRole('button', { name: 'Edit Ship the Daylight app', exact: true }).click();
  await dialog.getByLabel('Task name').fill('Ship Daylight today');
  await dialog.getByRole('button', { name: 'Save changes' }).click();
  await expect(dialog).not.toBeVisible();
  await page.getByRole('textbox', { name: 'Search tasks' }).fill('Ship Daylight');
  await expect(page.locator('.task-row')).toHaveCount(1);
  await page.getByRole('button', { name: 'Board view' }).click();
  await expect(page.locator('.board-column').filter({ hasText: 'In Progress' })).toContainText('Ship Daylight today');
  await page.getByRole('button', { name: 'Complete Ship Daylight today', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Reopen Ship Daylight today', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Save your workspace' }).click();
  await dialog.getByLabel('Your name').fill('Taylor');
  await dialog.getByLabel('Email address').fill('taylor-browser@example.com');
  await dialog.getByLabel('Password').fill('DaylightTest123!');
  await dialog.getByRole('button', { name: 'Create your account' }).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.getByRole('button', { name: 'Signed in as Taylor' })).toBeVisible();
  await expect(page.locator('.task-row')).toHaveCount(1);
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Save your workspace' })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Reopen Ship Daylight today', exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: 'Save your workspace' }).click();
  await dialog.getByRole('button', { name: 'Sign in', exact: true }).click();
  await dialog.getByLabel('Email address').fill('taylor-browser@example.com');
  await dialog.getByLabel('Password').fill('DaylightTest123!');
  await dialog.locator('form').getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(dialog).not.toBeVisible();
  await expect(page.getByRole('button', { name: 'Reopen Ship Daylight today', exact: true })).toBeVisible();
  page.once('dialog', confirmation => confirmation.accept());
  await page.getByRole('button', { name: 'Delete Ship Daylight today', exact: true }).click();
  await expect(page.locator('.task-row')).toHaveCount(0);
  expect(errors).toEqual([]);
});

test('mobile navigation, filters, and accessible task dialog work without horizontal overflow', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto('/');
  await expect(page.locator('.task-row')).toHaveCount(6);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole('button', { name: 'Open navigation' }).click();
  await page.getByRole('navigation', { name: 'Task lists', exact: true }).getByRole('button', { name: /Work/ }).click();
  await expect(page.locator('.task-row')).toHaveCount(3);
  await page.getByLabel('Filter by status').selectOption('Pending');
  await expect(page.locator('.task-row')).toHaveCount(1);
  await page.getByRole('button', { name: 'New task', exact: true }).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await expect(page.getByLabel('Task name')).toBeFocused();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('dialog')).not.toBeVisible();
  await expect(page.getByRole('button', { name: 'New task', exact: true })).toBeFocused();
});
